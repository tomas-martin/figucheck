// Generate all 252 stickers array
export const ALL_STICKERS: Sticker[] = (() => {
  const list: Sticker[] = [];
  let currentNum = 1;

  TEAMS.forEach((team) => {
    const isSpecialTeam = team.slug === 'leyendas';
    for (let slot = 1; slot <= team.stickerCount; slot++) {
      list.push({
        number: currentNum,
        teamId: team.id,
        teamName: team.name,
        teamShortName: team.shortName,
        slotNumber: slot,
        playerName: isSpecialTeam ? `Leyenda #${slot}` : `Jugador #${slot}`,
        isSpecial: isSpecialTeam
      });
      currentNum++;
    }
  });

  return list;
})();

export const TOTAL_STICKER_COUNT = ALL_STICKERS.length; // 252
